/**
 * 자사 서비스를 깎아내리는 글인가 — 발행 직전 마지막 방어.
 *
 * 2026-07-07~08-18 사이 봇이 "AI 1X2 예측 44% ㅋㅋ 인간이 더 낫네" 류의 자사 조롱 글을
 * 9건 발행했다. 원인은 토픽 guide 의 "가볍게 놀리는" 지시였지만, 프롬프트를 고쳐도
 * temperature 0.95 에서는 같은 결이 새어나올 수 있어 텍스트 단계에서 한 번 더 막는다.
 *
 * 우리 서비스를 가리키는 말과 비하 표현이 **같이** 있을 때만 막는다 — 경기 결과에 놀라는
 * "래피드 진짜 뭐하는 팀이냐" 같은 정상 글을 잡지 않기 위해서다.
 */
export function disparagesUs(text: string): boolean {
  // 본문이 "128경기 55%" 처럼 숫자만 말하고 주어를 생략해도 잡히도록, ai-report 토픽에
  // 항상 붙는 적중률 링크를 우리 얘기의 신호로 같이 본다(호출부가 appendix 까지 넘긴다).
  const us = /(AI|에이아이|예측|적중|모델|알고리즘|머신러닝|이 사이트|스코어베이스|predictions\/accuracy)/;
  if (!us.test(text)) return false;
  const slur =
    /(동전\s*던지|동전던지|무작위|랜덤이랑|랜덤과|찍는\s*것|찍기랑|쓸모\s*없|의미\s*없|돈\s*낭비|사기|형편없|구리네|믿을\s*게\s*못|못\s*믿|차라리|낫겠|나을\s*게\s*없|별\s*차이\s*없|다를\s*바\s*없|뭐하는\s*짓|뭐\s*하는\s*짓|이게\s*뭐하|광고\s*그만|업그레이드\s*먼저)/;
  return slur.test(text);
}
