export function searchTeamNamesByKo(q: string, limit = 30): string[] {
  const out: string[] = [];
  for (const [en, ko] of Object.entries(RAW)) {
    if (ko.includes(q)) {
      out.push(en);
      if (out.length >= limit) break;
    }
  }
  return out;
}

