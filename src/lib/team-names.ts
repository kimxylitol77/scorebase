// miss 면 Team.nameKo(TheSports 공식 미러, daily-official-korean 봇 적재), 그것도 없으면 영문 원본.
// 표기 교정은 이 파일의 사전에 추가할 것 — DB nameKo 는 봇이 매일 덮어쓴다.
export function teamDisplayKo(
  team: { name: string; nameKo?: string | null },
  league?: string,
): string {
  const dict = toKoreanTeamName(team.name, league);
  if (dict !== team.name.trim()) return dict; // 사전 hit
  return team.nameKo ?? dict;
}

export function toKoreanTeamName(
  name: string | undefined | null,
  league?: string,
): string {
  if (!name) return "";
  const trimmed = name.trim();
  const lower = trimmed.toLowerCase();
  const stripped = trimmed.replace(STRIP_RE, "").trim();
  const strippedLower = stripped.toLowerCase();

  if (league) {
    const lgMap = RAW_BY_LEAGUE[league];
    const lgLowerMap = RAW_BY_LEAGUE_LOWER[league];
    if (lgMap?.[trimmed]) return lgMap[trimmed];
    if (lgLowerMap?.[lower]) return lgLowerMap[lower];
    if (lgMap?.[stripped]) return lgMap[stripped];
    if (lgLowerMap?.[strippedLower]) return lgLowerMap[strippedLower];
  }

  if (RAW[trimmed]) return RAW[trimmed];
  if (RAW_LOWER[lower]) return RAW_LOWER[lower];
  if (RAW[stripped]) return RAW[stripped];
  if (RAW_LOWER[strippedLower]) return RAW_LOWER[strippedLower];
  // NPB 약자: league 인자 없이 호출돼도 풀네임→약자 적용 (MatchInsight 등 공통 컴포넌트).
  // 키가 고유한 한글 풀네임이라 타 리그와 충돌 없음.
  if (NPB_TEAM_SHORT_NAMES[trimmed]) return NPB_TEAM_SHORT_NAMES[trimmed];
  return trimmed;
}
