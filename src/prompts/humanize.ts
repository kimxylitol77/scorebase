// 심판봇 고쳐쓰기 프롬프트 — 규칙 채점기가 짚은 "AI 티"만 문체 수준에서 고치고, 숫자·헤딩·표·라벨은 글자 그대로 보존시킨다.

export const HUMANIZE_SYSTEM = `너는 한국어 스포츠 데이터 매체의 데스크 편집자다. 기자가 쓴 초고를 "고쳐" 쓴다. 새로 쓰지 않는다.
사실·수치·이름·순서를 바꾸지 않고, 읽는 사람이 기계가 쓴 글이라고 느끼게 하는 버릇만 걷어낸다.`;

export function buildHumanizePrompt(content: string, findings: string[], format: "md" | "html" = "md"): string {
  const keep =
    format === "html"
      ? `- "<p>" 로 시작하는 문단 줄만 고쳐라. 그 밖의 모든 줄(<h2>·<table>·<tr>·<figure>·<img>·<script>·<li>·<hr>, style 속성이 붙은 <p>)은 글자 그대로 둔다. 줄의 개수와 순서도 그대로다.
- 문단 안의 <a>·<strong> 태그는 그 안의 글자와 함께 그대로 둔다.`
      : `- "#"으로 시작하는 제목 줄, "|"로 시작하는 표 줄, "**"로 시작하고 📊 🎲 📈 🎯 이모지가 들어간 줄, "<!--" 주석 줄, {{ }} 토큰, 마크다운 링크는 글자 그대로 둔다.
- 제목 바로 아래 굵은 리드 문장과 마지막 면책 문장("본 분석은 …")은 그대로 둔다.`;
  return `아래 ${format === "html" ? "HTML" : "마크다운"} 초고를 고쳐라. 출력은 고친 ${format === "html" ? "HTML" : "마크다운"} 전문 하나뿐이다. 설명·머리말·코드펜스 금지.

## 반드시 지킬 것 (하나라도 어기면 원고 전체가 폐기된다)
- 숫자·퍼센트·스코어·날짜·이름은 한 글자도 바꾸지 말고, 빼지도 더하지도 마라. 원문의 모든 숫자가 그대로 남아야 한다.
${keep}
- 새로운 주장·사실·통계·비유·경험담을 넣지 마라. 문장을 지워야 한다면 그 문장의 숫자가 다른 곳에 남아 있을 때만 지워라.
- 번호 목록의 항목 수와 순서는 유지한다.
- 문장 종결어미의 체는 원문 그대로. 원문이 "~습니다/~입니다" 면 고친 글도 그렇게, 원문이 "~다" 면 "~다" 로. 섞지 마라.
- 분량은 원문의 0.8~1.2배.

## 고칠 것 (채점기가 이 원고에서 실제로 잡은 항목)
${findings.map((f) => `- ${f}`).join("\n")}

## 고치는 방법
- 문장 길이를 일부러 섞어라. 긴 문장 뒤에 짧은 문장을 둔다. 같은 길이의 문장이 세 개 연달아 오지 않게 한다.
- 문단마다 숫자가 없는 짧은 문장(15자 안팎)을 하나씩 둬라. 앞 문장의 숫자를 한마디로 받는 문장이면 된다. 예: "체급이 다르다." "선발 싸움이다." 단, 새 사실은 안 된다.
- 문장을 통째로 지우는 것보다 고치는 것이 먼저다. 숫자가 든 문장은 지우지 마라.
- "이는 ~을 보여준다/드러낸다/시사한다/의미한다" 식 마무리를 대부분 지워라. 근거를 말했으면 해설 문장을 덧붙이지 말고 다음으로 넘어간다.
- "극단적·극명한·명확한·압도적·결정적" 같은 강조어는 숫자가 이미 말하고 있으면 뺀다.
- 긴 줄표(—)는 쉼표나 마침표로 바꾼다. 단, 보존 대상 줄 안의 줄표는 건드리지 않는다.
- 볼드 소제목 한 줄 + 설명 문단 세트가 연달아 오면 절반쯤은 소제목을 없애고 첫 문장이 주제를 말하게 이어 붙여라. 📊 🎲 📈 🎯 라벨 줄은 예외다.
- "~할 것이다 / ~가능성이 높다 / ~것으로 보인다" 가 문단마다 반복되면 일부는 평서문으로 바꾼다.
- 어려운 한자어를 쉬운 말로. 다만 종목 용어(FIP, xG, Elo 등)는 그대로.

## 초고
${content}`;
}
