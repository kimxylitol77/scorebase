// 경기 후 전술 분석 아티클 프롬프트. buildTacticalContext 가 만든 데이터 텍스트를
// 받아, 주어진 숫자 밖 사실을 지어내지 못하게 하고 전술 리뷰 구조를 강제한다.
// 서술 방식은 유튜브 전술 채널(Tifo Football·The Athletic 전술 코너·엘미하의 전술노트·GED FOOTBALL)이
// 쓰는 "명제 → 장면 근거 → 숫자 확인 → 감독의 선택" 순서를 글로 옮긴 것이다.

import type { TacticalContext } from "@/lib/tactical/context";

const LEAGUE_NAME: Record<string, string> = {
  EPL: "프리미어리그",
  LALIGA: "라리가",
  BUNDESLIGA: "분데스리가",
  SERIE_A: "세리에 A",
  LIGUE_1: "리그 1",
  UCL: "챔피언스리그",
  K_LEAGUE_1: "K리그1",
  K_LEAGUE_2: "K리그2",
};

/**
 * 전문가 구성 — 팀 스타일 지표·분당 흐름·골 좌표·선수 스탯이 모두 있는 경기용(EPL).
 * 해외 전술 채널이 쓰는 순서를 글로 옮겼다. 명제 하나를 세우고, 두 팀의 설계 → 공을 가졌을 때 → 잃었을 때 →
 * 흐름이 바뀐 지점 → 골의 해부 → 선수 → 결론 순으로 그 명제를 증명한다. 도식은 코드가 섹션 끝에 끼운다.
 */
function buildProPrompt(ctx: TacticalContext, friendlyName: string): string {
  const hasGoals = ctx.insights.goals.length > 0;
  const hasHalves = ctx.insights.halves.length > 0;
  return `아래는 방금 끝난 ${friendlyName} 경기의 실제 데이터입니다. 이 데이터만 근거로, 전술 분석가가 쓴 한국어 경기 분석을 작성하세요.

[경기 데이터]
${ctx.text}

[이 글이 답해야 할 질문]
"이 경기는 왜 이렇게 끝났는가." 스코어를 다시 말하는 글이 아니라, 두 팀이 각각 무엇을 하려 했고 어느 쪽 계획이 통했는지를 설명하는 글입니다.
먼저 데이터를 읽고 명제 하나를 정하세요. 예를 들면 "점유는 내줬지만 박스 안 슈팅을 더 만든 쪽이 이겼다", "후반 교체 뒤 흐름이 넘어갔다" 같은 한 문장입니다.
글 전체가 그 명제를 증명해야 합니다. 명제와 상관없는 숫자는 쓰지 마세요.

[읽는 법 — 숫자를 전술로 옮기기]
- 점유율과 패스 수는 "누가 공을 오래 가졌나"만 말합니다. 주도권은 박스 안 슈팅·빅찬스·키패스와 같이 봐야 합니다. 점유가 높은데 박스 안 슈팅이 적으면 상대 수비 블록 밖에서 공을 돌린 것입니다.
- 롱볼 비중이 높고 패스 수가 적으면 직선적인 전개, 롱볼 비중이 낮고 패스 성공률이 높으면 짧게 풀어 나오는 전개입니다. 크로스 수는 측면을 얼마나 썼는지를 말합니다.
- 클리어와 태클+가로채기가 많은 팀은 자기 진영에서 버틴 시간이 길었다는 뜻입니다. 경합·공중볼 승률은 그 싸움에서 누가 이겼는지를 말합니다.
- 볼 소유 상실이 많은 팀은 위험을 감수하고 전진했거나 압박에 공을 잃었습니다. 어느 쪽인지는 상대의 태클+가로채기 수와 같이 판단하세요.
- 역습 슈팅은 전환 속도를 말합니다.
- [경기 흐름]은 득점이 아니라 공격 압력입니다. 흐름이 넘어간 구간을 찾고, 그 직전의 골·교체·카드([타임라인])와 연결해 "왜 넘어갔는가"를 설명하세요.${hasHalves ? "\n- [전후반 변화]에서 크게 달라진 항목이 하프타임 조정의 흔적입니다. 수치가 크게 바뀐 항목만 고르세요." : ""}${hasGoals ? "\n- [골 장면]의 시작 위치·연결 수·슈팅 위치로 득점 방식을 설명하세요. 연결 수가 많으면 조립된 공격, 적으면 전환이나 세컨드볼입니다." : ""}

[작성 규칙]
- 숫자는 [경기 데이터]에 적힌 값만, 적힌 그대로 쓰세요. 직접 더하거나 나누거나 비율을 새로 계산하지 마세요. 필요한 비율은 [스타일 지표]에 이미 계산돼 있습니다.
- 데이터에 없는 것은 쓰지 마세요. 패스맵·히트맵·압박 지표·수비 라인 높이·선수의 평균 위치·기대득점(xG)·특정 장면의 묘사(드리블 돌파, 선방 장면, 크로스의 궤적)는 데이터에 없습니다.
- [골 장면]에 없는 패스 형태(스루패스·컷백·원투)는 지어내지 마세요. "두 번의 연결 뒤 박스 안 중앙에서 마무리" 처럼 데이터에 있는 말로만 쓰세요.
- 포메이션은 배치입니다. 선수가 실제로 어디서 뛰었는지는 데이터에 없으니 "배치상" "설계상"이라고 쓰세요.
- 두 수의 크고 작음을 말하기 전에 두 수를 다시 비교하세요. "6회로 8회를 앞섰다" 같은 문장은 틀린 문장입니다.
- 골의 순서와 그때의 스코어는 [타임라인]에 적힌 순서와 "→ 2-1" 표기를 그대로 따르세요. 분이 빠른 골을 뒤에 일어난 일처럼 쓰지 마세요.
- 해석에는 근거 숫자를 한 문장 안에 하나씩 붙이세요. 한 문장에 숫자를 셋 이상 몰아넣지 마세요.
- 단정할 수 없는 해석은 "데이터상 ~로 읽힌다"로 쓰세요. 감독의 발언·의도·지시는 알 수 없습니다. 교체와 선발이라는 결정만 말하세요.
- [감독] 줄의 이름을 본문에서 언급하세요. 선수·팀·감독 이름은 데이터의 한글 표기를 글자 그대로 쓰세요.
- 홈/원정 수치를 뒤바꾸지 마세요.
- 같은 말을 되풀이하지 마세요. "중원 싸움이 치열했다" 같은, 어느 경기에나 쓸 수 있는 문장은 쓰지 마세요.
- 홍보성 과장, 베팅 유도 표현 금지.

[출력 형식]
- 마크다운. 첫 줄은 "# " 로 시작하는 제목. 스코어가 아니라 명제를 제목으로 삼으세요(낚시성 금지, 영문 단어 금지).
- 둘째 줄은 굵은 글씨 리드 한 문장. 최종 스코어를 "홈팀 2-1 원정팀" 처럼 숫자로 반드시 적고, 이어서 명제를 말하세요.
- [최근 폼]의 W/D/L 문자열은 그대로 쓰지 말고 "최근 5경기 1승 1무 3패"처럼 풀어 쓰세요.
- 아래 소제목(##)을 이 순서 그대로, 글자 그대로 쓰세요. 그림은 시스템이 각 섹션 끝에 자동으로 넣으니 "아래 그림" 같은 말은 쓰지 마세요.
  ## 두 팀의 설계
  ## 공을 가졌을 때
  ## 공을 잃었을 때
  ## 흐름이 바뀐 지점${hasGoals ? "\n  ## 골의 해부" : ""}
  ## 숫자가 가리킨 선수
  ## 결론과 다음 경기
- 각 섹션 2문단 안팎, 전체 2,600~3,200자. 길게 늘이지 말고 마지막 섹션까지 반드시 끝맺으세요. 표·목록 없이 문장으로 쓰세요.
- 모든 한국어 문장은 마침표로 끝냅니다. 콜론으로 문장을 끝내지 마세요.`;
}

export function buildTacticalAnalysisPrompt(ctx: TacticalContext): string {
  const friendlyName = LEAGUE_NAME[ctx.league] ?? ctx.league;
  if (ctx.pro) return buildProPrompt(ctx, friendlyName);
  const rich = ctx.text.includes("[타임라인]") || ctx.text.includes("선수 스탯]");
  // 데이터 유무에 따라 섹션·규칙을 뺀다 — 없는 데이터의 섹션을 남기면 모델이 채워 넣는다(K리그1 은 xG·선수 스탯·점유 대부분 없음).
  const hasTeamStats = ctx.hasXg || /\[점유율\]|\[슈팅\]/.test(ctx.text);
  const flowLabel = ctx.hasXg
    ? "점유·슈팅·xG 로 읽는 주도권"
    : hasTeamStats
      ? "점유·슈팅으로 읽는 주도권"
      : "선발 구성과 타임라인으로 읽는 주도권";

  const richRules = rich
    ? `- [타임라인]의 골·교체·카드는 이 경기의 유일한 "장면" 근거입니다. 시간 순으로 인용하되, 교체는 감독의 대응(무엇을 바꾸려 했는지)으로 해석하세요. 타임라인에 없는 장면(특정 패스·드리블·세이브 장면)은 묘사하지 마세요.
${
  ctx.hasPlayerStats
    ? `- [선수 스탯]의 평점·키패스·태클·듀얼·드리블·슈팅 숫자로 "누가 경기를 쥐었는지"를 말하세요. 거기 없는 개인 수치는 쓰지 마세요.`
    : `- 선수별 스탯(평점·패스·태클·슈팅 수)은 이 경기에 없습니다. 개인 수치를 하나도 쓰지 말고, 선수 평가는 타임라인의 골·도움·교체 사실로만 하세요.`
}
- 골의 도움 기록은 "도움"으로만 쓰세요. 크로스·컷백·스루패스 같은 패스 형태나 골 장면의 모양은 데이터에 없으니 지어내지 마세요.
- [감독] 줄의 이름을 반드시 본문에서 언급하고, 선발 구성과 교체 타이밍을 그 감독의 결정으로 서술하세요.
- 선수 이름은 [선발 XI]·[타임라인]·[선수 스탯]에 적힌 한글 표기를 글자 그대로 쓰세요. 영문 표기·임의 음역 금지.`
    : `- 득점자·어시스트·교체·부상은 데이터에 없습니다. "~가 득점에 관여했을 것" 같은 추측도 쓰지 마세요. 선발 명단은 역할(포지션) 설명에만 쓰세요.`;

  const structure = rich
    ? `  ## 한 줄 전술 요약
  ## 두 감독의 셋업 (포메이션·선발 구성·의도)
  ## 볼을 가졌을 때와 잃었을 때 (${flowLabel})
  ## 경기를 바꾼 장면들 (타임라인 순서대로 — 골·교체·카드)
${ctx.hasPlayerStats ? "  ## 숫자가 가리킨 선수 (선수 스탯 기반)\n" : ""}  ## 감독의 수 (교체 카드와 그 타이밍)
  ## 총평과 다음 경기 시사점`
    : `  ## 경기 요약
  ## 포메이션과 맞대결 구도
  ## 흐름을 가른 지점 (${ctx.hasXg ? "xG·슈팅·점유 해석" : "슈팅·점유 해석"})
  ## 키플레이어
  ## 총평`;
  // 재료가 적은 경기(xG·선수 스탯 없음)에 긴 분량을 요구하면 같은 말을 반복하는 얇은 글이 된다.
  const length = rich ? (ctx.hasXg || ctx.hasPlayerStats ? "2,400~3,200자" : "1,800~2,400자") : "1,500~2,000자";

  return `아래는 방금 끝난 ${friendlyName} 경기의 실제 데이터입니다. 이 데이터만 근거로, 전술 분석가가 쓴 한국어 경기 리뷰를 작성하세요.

[경기 데이터]
${ctx.text}

[관점 — 전술 분석가처럼]
- 결론(이 경기를 가른 전술적 요인 하나)을 먼저 세우고, 장면(타임라인)과 숫자(점유·xG·슈팅·선수 스탯)로 그 결론을 증명하는 순서로 쓰세요.
- 포메이션은 숫자 나열이 아니라 "맞물림"으로 설명하세요. 예를 들어 4-2-3-1 대 4-2-3-1 이면 2명의 중앙 미드필더끼리 맞붙어 측면 폭과 하프스페이스 활용이 승부처가 된다는 식으로, 데이터에 적힌 포메이션·선수 포지션에서 논리적으로 끌어낸 것만 쓰세요.
- 점유율이 높은 쪽이 주도권을 쥐었는지, 아니면 상대가 내려앉힌 결과인지는 슈팅·피슈팅·xG 와 함께 판단하세요. 점유율 하나로 단정하지 마세요.
- 교체는 감독의 의사결정입니다. 시간대·바꾼 포지션으로 "무엇을 지키려 했는가/무엇을 뒤집으려 했는가"를 읽어내되, 데이터에 없는 지시 내용은 지어내지 마세요.
- 한 문장에 숫자를 두 개 이상 몰아넣지 말고, 숫자는 주장을 받치는 자리에만 두세요.

[작성 규칙]
- 위 데이터에 있는 숫자·포메이션·선수·감독 이름만 사용하세요. 데이터에 없는 통계(압박 지표·히트맵·패스맵 등)나 사실(부상·이적·발언·관중 수·경기 전 기자회견)은 지어내지 마세요.
- 추측이 필요하면 "데이터상 ~로 보인다" 식으로 근거가 데이터임을 드러내세요. 단정적 창작은 금지.
${richRules}
- 팀명은 입력 데이터의 한글 표기를 글자 그대로 사용하세요(임의 음역·영문 표기 금지).
- 홈/원정 수치를 뒤바꾸지 마세요. 각 수치는 데이터에 적힌 팀에만 붙입니다.
${ctx.hasXg ? "- xG 와 실제 득점의 차이는 마무리 효율 또는 운으로 해석할 수 있습니다." : "- 이 경기에는 xG(기대득점) 데이터가 없습니다. xG·기대득점을 언급하거나 추정하지 마세요."}${hasTeamStats ? "" : "\n- 점유율·슈팅 수 등 팀 통계도 없습니다. 퍼센트나 슈팅 개수를 쓰지 마세요."}
- 홍보성 과장, 베팅 유도 표현 금지. 담백하되 확신 있는 분석가 톤.

[출력 형식]
- 마크다운. 첫 줄은 "# " 로 시작하는 제목(경기 결과와 전술적 핵심을 담되 낚시성 금지).
- 둘째 줄은 굵은 글씨 리드 한 문장. 리드에 최종 스코어를 "홈팀 1-0 원정팀" 또는 "원정팀이 3-0으로 승리" 처럼 숫자로 반드시 적으세요("3골" 같은 표현만으로는 부족합니다).
- [최근 폼]의 W/D/L 문자열(예: DWLLL)을 그대로 쓰지 말고 "최근 5경기 1승 1무 3패"처럼 풀어 쓰세요. 승·무·패 수는 문자열을 정확히 세어 적으세요.
- 다음 구조를 소제목(##)으로 포함:
${structure}
- 각 섹션 2~4문단, 전체 ${length}. 데이터를 문장 속에 녹여 서술(표·목록 나열 금지).
- 모든 한국어 문장은 마침표로 끝냅니다. 콜론으로 문장을 끝내지 마세요.`;
}
