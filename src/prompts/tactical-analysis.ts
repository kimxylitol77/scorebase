// 경기 후 전술 분석 아티클 프롬프트. buildTacticalContext 가 만든 데이터 텍스트를
// 받아, 주어진 숫자 밖 사실을 지어내지 못하게 하고 전술 리뷰 구조를 강제한다.
// 서술 방식은 유튜브 전술 채널(Tifo Football·The Athletic 전술 코너·엘미하의 전술노트·GED FOOTBALL)이
// 쓰는 "명제 → 장면 근거 → 숫자 확인 → 감독의 선택" 순서를 글로 옮긴 것이다.

import type { TacticalContext } from "@/lib/tactical/context";

const LEAGUE_NAME: Record<string, string> = {
  EPL: "프리미어리그",
  LALIGA: "라리가",
  BUNDESLIGA: "분데스리가",
  SERIE_A: "세리에 A",
  LIGUE_1: "리그 1",
  UCL: "챔피언스리그",
};

export function buildTacticalAnalysisPrompt(ctx: TacticalContext): string {
  const friendlyName = LEAGUE_NAME[ctx.league] ?? ctx.league;
  const rich = ctx.text.includes("[타임라인]") || ctx.text.includes("선수 스탯]");

  const richRules = rich
    ? `- [타임라인]의 골·교체·카드는 이 경기의 유일한 "장면" 근거입니다. 시간 순으로 인용하되, 교체는 감독의 대응(무엇을 바꾸려 했는지)으로 해석하세요. 타임라인에 없는 장면(특정 패스·드리블·세이브 장면)은 묘사하지 마세요.
- [선수 스탯]의 평점·키패스·태클·듀얼·드리블·슈팅 숫자로 "누가 경기를 쥐었는지"를 말하세요. 거기 없는 개인 수치는 쓰지 마세요.
- [감독] 줄의 이름을 반드시 본문에서 언급하고, 선발 구성과 교체 타이밍을 그 감독의 결정으로 서술하세요.
- 선수 이름은 [선발 XI]·[타임라인]·[선수 스탯]에 적힌 한글 표기를 글자 그대로 쓰세요. 영문 표기·임의 음역 금지.`
    : `- 득점자·어시스트·교체·부상은 데이터에 없습니다. "~가 득점에 관여했을 것" 같은 추측도 쓰지 마세요. 선발 명단은 역할(포지션) 설명에만 쓰세요.`;

  const structure = rich
    ? `  ## 한 줄 전술 요약
  ## 두 감독의 셋업 (포메이션·선발 구성·의도)
  ## 볼을 가졌을 때와 잃었을 때 (점유·슈팅·xG 로 읽는 주도권)
  ## 경기를 바꾼 장면들 (타임라인 순서대로 — 골·교체·카드)
  ## 숫자가 가리킨 선수 (선수 스탯 기반)
  ## 감독의 수 (교체 카드와 그 타이밍)
  ## 총평과 다음 경기 시사점`
    : `  ## 경기 요약
  ## 포메이션과 맞대결 구도
  ## 흐름을 가른 지점 (xG·슈팅·점유 해석)
  ## 키플레이어
  ## 총평`;

  return `아래는 방금 끝난 ${friendlyName} 경기의 실제 데이터입니다. 이 데이터만 근거로, 전술 분석가가 쓴 한국어 경기 리뷰를 작성하세요.

[경기 데이터]
${ctx.text}

[관점 — 전술 분석가처럼]
- 결론(이 경기를 가른 전술적 요인 하나)을 먼저 세우고, 장면(타임라인)과 숫자(점유·xG·슈팅·선수 스탯)로 그 결론을 증명하는 순서로 쓰세요.
- 포메이션은 숫자 나열이 아니라 "맞물림"으로 설명하세요. 예를 들어 4-2-3-1 대 4-2-3-1 이면 2명의 중앙 미드필더끼리 맞붙어 측면 폭과 하프스페이스 활용이 승부처가 된다는 식으로, 데이터에 적힌 포메이션·선수 포지션에서 논리적으로 끌어낸 것만 쓰세요.
- 점유율이 높은 쪽이 주도권을 쥐었는지, 아니면 상대가 내려앉힌 결과인지는 슈팅·피슈팅·xG 와 함께 판단하세요. 점유율 하나로 단정하지 마세요.
- 교체는 감독의 의사결정입니다. 시간대·바꾼 포지션으로 "무엇을 지키려 했는가/무엇을 뒤집으려 했는가"를 읽어내되, 데이터에 없는 지시 내용은 지어내지 마세요.
- 한 문장에 숫자를 두 개 이상 몰아넣지 말고, 숫자는 주장을 받치는 자리에만 두세요.

[작성 규칙]
- 위 데이터에 있는 숫자·포메이션·선수·감독 이름만 사용하세요. 데이터에 없는 통계(압박 지표·히트맵·패스맵 등)나 사실(부상·이적·발언·관중 수·경기 전 기자회견)은 지어내지 마세요.
- 추측이 필요하면 "데이터상 ~로 보인다" 식으로 근거가 데이터임을 드러내세요. 단정적 창작은 금지.
${richRules}
- 팀명은 입력 데이터의 한글 표기를 글자 그대로 사용하세요(임의 음역·영문 표기 금지).
- 홈/원정 수치를 뒤바꾸지 마세요. 각 수치는 데이터에 적힌 팀에만 붙입니다.
- xG 와 실제 득점의 차이는 마무리 효율 또는 운으로 해석할 수 있습니다.
- 홍보성 과장, 베팅 유도 표현 금지. 담백하되 확신 있는 분석가 톤.

[출력 형식]
- 마크다운. 첫 줄은 "# " 로 시작하는 제목(경기 결과와 전술적 핵심을 담되 낚시성 금지).
- 둘째 줄은 굵은 글씨 리드 한 문장.
- 다음 구조를 소제목(##)으로 포함:
${structure}
- 각 섹션 2~4문단, 전체 ${rich ? "2,400~3,200자" : "1,500~2,000자"}. 데이터를 문장 속에 녹여 서술(표·목록 나열 금지).
- 모든 한국어 문장은 마침표로 끝냅니다. 콜론으로 문장을 끝내지 마세요.`;
}
