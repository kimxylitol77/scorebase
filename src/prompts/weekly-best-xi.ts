// 수치·이름은 주입값 그대로. 야구 주간 베스트(baseball-weekly-players)와 같은 골격.
import { weeklyXiBrief, type WeeklyBestXi } from "@/lib/soccer/weekly-best-xi";

// 심판관(article-judge)에 넘길 이 글 유형의 체크 항목.
export const WEEKLY_XI_RUBRIC = `[구조]
- H1 제목 1개(맨 위). 이모지·클릭베이트 없이, 이번 주 MVP 나 최고 활약을 담을 것.
- 제목 아래 굵은 한 줄 요약(> **한눈에 요약**) blockquote.
- markdown 표 1개 필수: '주간 베스트 XI' 표(평점·선수·소속·포지션·기록).
- 마지막 섹션은 '더 보기'. 별도 '결론' 헤딩 없음.
[AEO — 답변 우선]
- 각 ## 섹션은 첫 1~2문장에서 결론부터 제시.
[GEO — 자체 데이터]
- 우리 집계(평점 기반 베스트 XI·MVP) 수치가 본문에 실제로 인용되어 있을 것.
[페르소나·톤]
- Scorebase 분석 기자체(단정한 문어체). 데이터 저널리즘 톤.
- 이모지·클릭베이트 어휘 금지. 베팅·픽 추천·배당 언급 금지.
- 한국어 문장은 마침표로 끝냄(콜론 종결 금지).
[분량] 본문 1,800~2,800자(표 포함).`;

export function buildWeeklyXiPrompt(w: WeeklyBestXi, leagueKo: string): string {
  return `${leagueKo} ${w.from}~${w.to} 주간 베스트 XI 와 MVP 를 소개하는 글을 한국어로 작성하라.

## 실측 데이터 (그대로 인용 — 재계산·창작 금지)
${weeklyXiBrief(w, leagueKo)}

## 글 구조
1. H1 제목 — 이번 주 MVP 나 최고 활약을 담되 이모지·과장 어휘 없이.
2. 굵은 한 줄 요약 blockquote (> **한눈에 요약** 로 시작).
3. ## 이번 주 MVP — 평점과 기록으로 왜 최고였는지. 2~3문단.
4. ## 주간 베스트 XI — markdown 표(평점 | 선수 | 소속 | 포지션 | 기록) 후 포지션별 짧은 코멘트.
5. ## 이번 주 흐름 — 경기 결과에서 읽히는 리그 판도. 단, 제공된 결과 안에서만.
6. ## 더 보기 — 다음 라운드 관전 포인트를 한 문단.

## 반드시 지킬 것
- 평점·골·도움은 위 데이터의 값만 쓴다. 없는 수치(슈팅·패스 성공률·xG 등)는 언급하지 않는다.
- 제공되지 않은 경기·장면·발언을 지어내지 않는다. 이 주에 없는 팀은 언급하지 않는다.
- 표본이 ${w.matchCount}경기뿐이라는 점을 과장하지 않는다 — 시즌 단정 금지.
- 이모지 금지. 문장은 마침표로 끝낸다.`;
}
